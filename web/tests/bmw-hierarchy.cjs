const {chromium} = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
  const browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_PATH || undefined,args:['--no-sandbox']});
  const page = await browser.newPage(); const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.CAR_SPOTTER_URL || 'http://127.0.0.1:8000');
  await page.locator('#alphabet [data-letter=B]').click();
  await page.locator('[data-level=brand][data-value=BMW]').click();
  await page.locator('[data-level=model][data-value="autoria:9:3219"]').click();
  await page.locator('#search').fill('E36');
  assert.equal(await page.locator('#cars [data-level=family]').count(),1);
  await page.locator('#cars [data-level=family]').click();
  const phases=page.locator('#cars [data-level=generation]');assert.equal(await phases.count(),2);
  assert.match(await phases.nth(0).innerText(),/Pre-facelift/);assert.match(await phases.nth(1).innerText(),/Facelift/);
  await phases.first().click();
  for(const label of ['Sedan','Wagon','Coupé'])assert.equal(await page.locator('#cars .car-name').filter({hasText:new RegExp('^'+label+'$')}).count(),1);
  await page.locator('#cars [data-level=body]').filter({hasText:'Coupé'}).click();
  const engine=page.locator('[data-engine="320i"]');assert.equal(await engine.count(),1);
  const link=engine.locator('..').locator('a');
  assert.match(new URL(await link.getAttribute('href')).searchParams.get('q'),/BMW 3 Series E36 Pre-facelift .*Coupé 320i/);
  await engine.click();await page.locator('#log-engine').click();
  assert.equal(await page.locator('#generation').inputValue(),'autoria:9:3219:generation:10065');
  assert.match(await page.locator('#body-style').inputValue(),/SportsCar$/);
  assert.equal(await page.locator('#engine').inputValue(),'320i');
  await page.locator('#note').fill('Hierarchy test');
  await page.locator('#log-form [type=submit]').click();await page.locator('#log').waitFor({state:'hidden'});
  assert.equal(await page.locator('#score-total').innerText(),'22');
  await page.locator('#breadcrumbs [data-level=generation]').click();
  await page.locator('#cars [data-level=body]').filter({hasText:'Wagon'}).click();
  await page.locator('[data-engine="320i"]').click();await page.locator('#log-engine').click();
  await page.locator('#log-form [type=submit]').click();await page.locator('#log').waitFor({state:'hidden'});
  assert.equal(await page.locator('#score-total').innerText(),'22'); // no body/engine point farming
  await page.reload();await page.locator('#count').filter({hasText:'1'}).waitFor();
  await page.locator('#garage-tab').click();assert.equal(await page.locator('#sightings article').count(),2);
  assert.match(await page.locator('#sightings').innerText(),/Coupé/);assert.match(await page.locator('#sightings').innerText(),/Wagon/);
  assert.match(await page.locator('#sightings').innerText(),/320i/);
  await page.locator('#alphabet [data-letter=B]').click();
  await page.locator('[data-level=brand][data-value=BMW]').click();
  const ring=page.locator('[data-value="autoria:9:3219"] .completion-circle');
  assert.equal(await ring.getAttribute('data-completed'),'1');
  const count=await page.evaluate(async()=>{const c=(await(await fetch('./catalogue.json')).json()).find(c=>c.id==='autoria:9:3219');return c.generationFamilies.length});
  assert.equal(Number(await ring.getAttribute('data-total')),count);
  await page.setViewportSize({width:390,height:844});assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(errors,[]);await browser.close();console.log('PASS: BMW > 3 Series > E36 > version > body > engine; persistence, score deduplication, grouped completion, Google context, mobile layout');
})().catch(e=>{console.error(e);process.exit(1)});
