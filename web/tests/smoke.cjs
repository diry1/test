const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_PATH || undefined, args:['--no-sandbox']});
  const page = await browser.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.CAR_SPOTTER_URL || 'http://127.0.0.1:8000');
  await page.locator('#folder-title').filter({hasText:'A · Brands'}).waitFor();
  assert.equal(await page.locator('#alphabet [data-letter=A]').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#alphabet [data-letter=""]').count(), 0);
  await page.locator('#alphabet [data-letter=B]').click();
  const expectedB = ['BAIC','Barkas','Baw','Beijing','Bentley','BMW','BMW-Alpina','Bogdan','Brilliance','Bristol','Buick','BYD'];
  assert.deepEqual(await page.locator('#cars [data-level=brand] .car-name').allTextContents(), expectedB);
  assert.equal(await page.locator('#additional-section').isVisible(), false);
  await page.locator('[data-expand-brands]').click();
  const extraB = await page.locator('#additional-brands .car-name').allTextContents();
  assert.ok(extraB.length > 0);
  assert.ok(extraB.every(name => name.startsWith('B') && !expectedB.includes(name)));
  assert.deepEqual(extraB, [...extraB].sort((a,b) => a.localeCompare(b)));
  await page.locator('#additional-brands [data-level=brand]').first().click();
  await page.locator('#breadcrumbs [data-level=root]').click();
  assert.match(await page.locator('#folder-title').innerText(), /^B/);
  await page.locator('#alphabet [data-letter=A]').click();
  assert.equal(await page.locator('#additional-section').isVisible(), false);
  await page.locator('#alphabet [data-letter=P]').click();
  await page.locator('#search').fill('Porsche');
  await page.locator('#cars .card').first().click();
  assert.match(await page.locator('#folder-title').innerText(), /Porsche models/);
  await page.locator('#cars .card').first().click();
  assert.match(await page.locator('#folder-title').innerText(), /generations/);
  await page.locator('#open-log').click();
  await page.locator('#note').fill('Seen near the station <script>alert(1)</script>');
  await page.locator('#photo').setInputFiles({name:'test.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aX1cAAAAASUVORK5CYII=','base64')});
  await page.locator('#preview').waitFor({state:'visible'});
  await page.locator('#log-form [type=submit]').click();
  await page.locator('#log').waitFor({state:'hidden'});
  assert.ok(Number((await page.locator('#score-total').innerText()).replaceAll(',', '')) > 0);
  await page.locator('#garage-tab').click();
  assert.equal(await page.locator('#sightings article').count(),1);
  assert.equal(await page.locator('.sighting-photo').count(),1);
  assert.match(await page.locator('#sightings').innerText(), /<script>alert\(1\)<\/script>/);
  await page.evaluate(async () => {
    const db = await new Promise((resolve, reject) => { const r = indexedDB.open('car-spotter', 1); r.onsuccess = () => resolve(r.result); r.onerror = reject; });
    await new Promise((resolve, reject) => {
      const tx = db.transaction('sightings', 'readwrite');
      const store = tx.objectStore('sightings');
      const r = store.getAll(); r.onsuccess = () => store.put({...r.result[0], generationLabel:'ІІ поколiння (FL) · 2000–2005'});
      tx.oncomplete = resolve; tx.onerror = reject;
    });
    db.close();
  });
  await page.reload();
  await page.locator('#count').filter({hasText:'1'}).waitFor();
  assert.equal(await page.locator('#score-total').innerText(), '21');
  await page.locator('#garage-tab').click();
  assert.equal(await page.locator('#sightings article').count(),1);
  assert.match(await page.locator('#sightings').innerText(), /II Generation \(FL\)/);
  const names = await page.evaluate(async () => (await (await fetch('./catalogue.json')).json()).flatMap(c => c.generations.map(g => g.name)));
  assert.ok(names.every(name => !/покол[іi]ння/i.test(name)));
  const download = page.waitForEvent('download'); await page.locator('#export').click();
  assert.match((await download).suggestedFilename(), /^car-spotter-.*\.json$/);
  page.once('dialog', d => d.accept()); await page.locator('[data-delete]').click();
  await page.locator('#count').filter({hasText:'0'}).waitFor();
  assert.equal(await page.locator('#score-total').innerText(), '0');
  await page.locator('#catalogue-tab').click();
  await page.locator('#search').fill('zzzz-no-such-car');
  assert.match(await page.locator('#cars').innerText(), /No matches/);
  await page.setViewportSize({width:390,height:844});
  await page.locator('#search').fill('BMW');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
  await page.locator('#breadcrumbs [data-level=root]').click();
  await page.locator('#alphabet [data-letter=A]').click();
  await page.locator('#search').fill('Alfa Romeo');
  await page.locator('#cars .card').filter({hasText:'Alfa Romeo'}).first().click();
  const generationModel = await page.evaluate(async () => (await (await fetch('./catalogue.json')).json()).find(c => c.brand === 'Alfa Romeo' && c.generations.length));
  await page.locator('#search').fill(generationModel.name);
  await page.locator(`[data-level="model"][data-value="${generationModel.id}"]`).click();
  await page.locator('#cars [data-level=generation]').first().click();
  assert.match(await page.locator('#folder-title').innerText(), /Specifications/);
  assert.match(await page.locator('#folder-info').innerText(), /Available specifications/);
  await page.locator('#cars [data-spec]').first().click();
  await page.locator('#log-spec').click();
  assert.notEqual(await page.locator('#specification').inputValue(), '');
  assert.notEqual(await page.locator('#generation').inputValue(), '');
  await page.locator('#log-form [type=submit]').click();
  await page.locator('#log').waitFor({state:'hidden'});
  await page.locator('#garage-tab').click();
  assert.equal(await page.locator('#sightings article').count(),1);
  await page.locator('#catalogue-tab').click();
  await page.locator('#breadcrumbs [data-level=root]').click();
  await page.locator('#alphabet [data-letter=B]').click();
  await page.locator('#search').fill('BMW');
  await page.locator('#cars [data-level=brand][data-value=BMW]').click();
  await page.locator('#search').fill('3 Series');
  await page.locator('[data-level=model][data-value="autoria:9:3219"]').click();
  for (const name of ['E36', 'F30']) {
    await page.locator('#search').fill(name);
    await page.locator(`#cars [data-level=family][data-value="autoria:9:3219:family:${name}"]`).click();
    assert.match(await page.locator('#folder-title').innerText(), /Facelift versions/);
    await page.locator('#cars [data-level=generation]').first().click();
    assert.match(await page.locator('#folder-title').innerText(), /Body styles/);
    await page.locator('#cars [data-level=body]').first().click();
    assert.match(await page.locator('#results').innerText(), /specifications/);
    assert.ok(await page.locator('#cars [data-engine]').count() > 0);
    await page.locator('#breadcrumbs [data-level=model]').click();
  }
  assert.equal(await page.locator('#score-total').innerText(), '22');
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: brand → model → generation → specifications, search, photo + note save, persistence, export, deletion, empty search, mobile layout; no browser errors.');
})().catch(e => { console.error(e); process.exit(1); });
