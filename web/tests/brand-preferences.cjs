const {chromium} = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_PATH || undefined, args:['--no-sandbox']});
  const page = await browser.newPage();
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto(process.env.CAR_SPOTTER_URL || 'http://127.0.0.1:8000');
  await page.locator('#alphabet [data-letter=B]').click();
  const menu = brand => page.locator(`[data-brand-settings="${brand}"]`);
  await menu('BMW').locator('summary').click();
  assert.equal(await page.locator('#folder-title').innerText(),'B · Brands');
  await menu('BMW').locator('[data-brand-action=hide]').click();
  assert.equal(await page.locator('#cars [data-value=BMW]').count(),0);
  assert.equal(await page.locator('#additional-brands [data-value=BMW]').count(),1);
  await page.reload(); await page.locator('#alphabet [data-letter=B]').click();
  assert.equal(await page.locator('#cars [data-value=BMW]').count(),0);
  await page.locator('[data-expand-brands]').click();
  const extra = await page.locator('#additional-brands [data-level=brand]').first().getAttribute('data-value');
  await menu(extra).locator('summary').click();
  await menu(extra).locator('[data-brand-action=show]').click();
  const names = await page.locator('#cars [data-level=brand] .car-name').allTextContents();
  assert(names.includes(extra)); assert.deepEqual(names,[...names].sort((a,b)=>a.localeCompare(b)));
  await page.reload(); await page.locator('#alphabet [data-letter=B]').click();
  assert.equal(await page.locator(`#cars [data-value="${extra}"]`).count(),1);
  await page.locator('[data-expand-brands]').click();
  await menu('BMW').locator('summary').click();
  await menu('BMW').locator('[data-brand-action=show]').click();
  assert.equal(await page.locator('#cars [data-value=BMW]').count(),1);
  await page.evaluate(()=>{Storage.prototype.setItem=()=>{throw new Error('Storage blocked')};});
  await menu('BMW').locator('summary').click();
  await menu('BMW').locator('[data-brand-action=hide]').click();
  assert.match(await page.locator('#status').innerText(),/Could not save/);
  assert.equal(await page.locator('#cars [data-value=BMW]').count(),1);
  await page.setViewportSize({width:390,height:844});
  await page.keyboard.press('Escape');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: brand hide, promotion, alphabetical placement, persistence, recovery, storage failure, mobile layout');
})().catch(e=>{console.error(e);process.exit(1)});
